import pytest

KINDS = ["notes", "summaries"]


def create(env, kind, **fields):
    body = {"title": "测试标题", **fields}
    r = env.client.post(f"/api/admin/{kind}", json=body)
    assert r.status_code == 201, r.text
    return r.json()["data"]


def publish(env, kind, item_id):
    r = env.client.patch(f"/api/admin/{kind}/{item_id}", json={"visibility": "public", "status": "published"})
    assert r.status_code == 200, r.text


@pytest.mark.parametrize("kind", KINDS)
def test_new_content_is_private_draft_and_invisible(admin, kind):
    item = create(admin, kind, title="Hello World", body="# hi")
    assert item["visibility"] == "private" and item["status"] == "draft"
    admin.logout()
    assert admin.client.get(f"/api/public/{kind}").json()["data"] == []
    assert admin.client.get(f"/api/public/{kind}/{item['id']}").status_code == 404


@pytest.mark.parametrize("kind", KINDS)
def test_private_draft_and_missing_are_indistinguishable(admin, kind):
    item = create(admin, kind, title="secret")
    admin.logout()
    private = admin.client.get(f"/api/public/{kind}/{item['id']}")
    missing = admin.client.get(f"/api/public/{kind}/does-not-exist")
    assert private.status_code == missing.status_code == 404
    assert private.json() == missing.json()


@pytest.mark.parametrize("kind", KINDS)
def test_public_requires_both_public_and_published(admin, kind):
    a = create(admin, kind, title="a", visibility="public", status="draft")
    b = create(admin, kind, title="b", visibility="private", status="published")
    c = create(admin, kind, title="c", visibility="public", status="published")
    admin.logout()
    ids = [x["id"] for x in admin.client.get(f"/api/public/{kind}").json()["data"]]
    assert ids == [c["id"]]
    assert admin.client.get(f"/api/public/{kind}/{a['id']}").status_code == 404
    assert admin.client.get(f"/api/public/{kind}/{b['id']}").status_code == 404


@pytest.mark.parametrize("kind", KINDS)
def test_public_shapes_and_no_leak(admin, kind):
    item = create(admin, kind, title="Shape", summary="s", category="学习", tags=["a", "b"], body="正文")
    publish(admin, kind, item["id"])
    admin.logout()
    listed = admin.client.get(f"/api/public/{kind}").json()["data"][0]
    assert "body" not in listed
    detail = admin.client.get(f"/api/public/{kind}/{item['id']}").json()["data"]
    assert detail["body"] == "正文" and detail["tags"] == ["a", "b"] and detail["category"] == "学习"
    for forbidden in ("visibility", "status", "pk", "created_at", "updated_at"):
        assert forbidden not in listed and forbidden not in detail


@pytest.mark.parametrize("kind", KINDS)
def test_slug_autogenerated_and_deduplicated(admin, kind):
    first = create(admin, kind, title="Same Title")
    second = create(admin, kind, title="Same Title")
    assert first["id"] != second["id"]
    assert first["id"] and second["id"].startswith(first["id"])


@pytest.mark.parametrize("kind", KINDS)
def test_explicit_id_and_conflict(admin, kind):
    create(admin, kind, id="my-id")
    r = admin.client.post(f"/api/admin/{kind}", json={"title": "x", "id": "my-id"})
    assert r.status_code == 409 and r.json()["error"]["code"] == "ID_CONFLICT"


@pytest.mark.parametrize("bad", ["Has Space", "UPPER", "-lead", "a/b", "a" * 81])
def test_invalid_slug_rejected(admin, bad):
    r = admin.client.post("/api/admin/notes", json={"title": "x", "id": bad})
    assert r.status_code == 422


def test_notes_and_summaries_are_separate_tables(admin):
    create(admin, "notes", id="same")
    create(admin, "summaries", id="same")  # 不同表，id 可以相同
    publish(admin, "notes", "same")
    admin.logout()
    assert admin.client.get("/api/public/notes/same").status_code == 200
    assert admin.client.get("/api/public/summaries/same").status_code == 404


def test_update_autobumps_updated_only_for_content_edits(admin):
    item = create(admin, "notes", title="x", updated="2020-01-01")
    assert item["updated"] == "2020-01-01"
    r = admin.client.patch(f"/api/admin/notes/{item['id']}", json={"visibility": "public"})
    assert r.json()["data"]["updated"] == "2020-01-01"  # 仅改可见性不动 updated
    r = admin.client.patch(f"/api/admin/notes/{item['id']}", json={"body": "new"})
    assert r.json()["data"]["updated"] != "2020-01-01"
    r = admin.client.patch(
        f"/api/admin/notes/{item['id']}", json={"body": "again", "updated": "2021-02-03"}
    )
    assert r.json()["data"]["updated"] == "2021-02-03"  # 显式给出则以显式为准


def test_update_validation(admin):
    item = create(admin, "notes")
    url = f"/api/admin/notes/{item['id']}"
    assert admin.client.patch(url, json={}).status_code == 422
    assert admin.client.patch(url, json={"title": None}).status_code == 422
    assert admin.client.patch(url, json={"visibility": "secret"}).status_code == 422
    assert admin.client.patch(url, json={"status": "archived"}).status_code == 422
    assert admin.client.patch("/api/admin/notes/nope", json={"title": "x"}).status_code == 404


def test_rename_id_conflict(admin):
    create(admin, "notes", id="one")
    create(admin, "notes", id="two")
    r = admin.client.patch("/api/admin/notes/one", json={"id": "two"})
    assert r.status_code == 409
    r = admin.client.patch("/api/admin/notes/one", json={"id": "three"})
    assert r.status_code == 200 and r.json()["data"]["id"] == "three"


def test_tags_are_cleaned_and_limited(admin):
    item = create(admin, "notes", tags=[" a ", "a", "", "b"])
    assert item["tags"] == ["a", "b"]
    too_many = admin.client.post("/api/admin/notes", json={"title": "x", "tags": [str(i) for i in range(21)]})
    assert too_many.status_code == 422
    too_long = admin.client.post("/api/admin/notes", json={"title": "x", "tags": ["x" * 31]})
    assert too_long.status_code == 422


def test_delete(admin):
    item = create(admin, "notes")
    assert admin.client.delete(f"/api/admin/notes/{item['id']}").status_code == 200
    assert admin.client.get(f"/api/admin/notes/{item['id']}").status_code == 404
    assert admin.client.delete(f"/api/admin/notes/{item['id']}").status_code == 404


def test_admin_list_filters_and_sees_everything(admin):
    a = create(admin, "notes", title="Alpha")
    create(admin, "notes", title="Beta", visibility="public", status="published")
    assert len(admin.client.get("/api/admin/notes").json()["data"]) == 2
    only_draft = admin.client.get("/api/admin/notes", params={"status": "draft"}).json()["data"]
    assert [x["id"] for x in only_draft] == [a["id"]]
    found = admin.client.get("/api/admin/notes", params={"q": "alp"}).json()["data"]
    assert [x["id"] for x in found] == [a["id"]]
    assert admin.client.get("/api/admin/notes", params={"limit": 0}).status_code == 422


def test_public_ordering_by_updated_then_date(admin):
    old = create(admin, "notes", title="old", date="2020-01-01", visibility="public", status="published")
    new = create(admin, "notes", title="new", date="2019-01-01", updated="2024-01-01",
                 visibility="public", status="published")
    mid = create(admin, "notes", title="mid", date="2022-01-01", visibility="public", status="published")
    admin.logout()
    ids = [x["id"] for x in admin.client.get("/api/public/notes").json()["data"]]
    assert ids == [new["id"], mid["id"], old["id"]]


def test_admin_endpoints_require_login(env):
    for method, url in [
        ("get", "/api/admin/notes"),
        ("post", "/api/admin/notes"),
        ("get", "/api/admin/summaries/x"),
        ("patch", "/api/admin/summaries/x"),
        ("delete", "/api/admin/notes/x"),
        ("get", "/api/admin/files"),
        ("post", "/api/admin/files"),
        ("get", "/api/admin/files/x/content"),
    ]:
        r = getattr(env.client, method)(url)
        assert r.status_code == 401, (method, url)
